// Висота трикутника за площею S і стороною a: h = 2*S / a
#include <iostream>
using namespace std;

int main() {
    double S, a;                       // вхідні дані
    cout << "Введіть площу трикутника S: ";
    cin >> S;
    cout << "Введіть довжину сторони a: ";
    cin >> a;

    if (S <= 0 || a <= 0) {
        cout << "Помилка: площа і сторона мають бути додатними!" << endl;
        return 1;
    }

    double twoS = 2 * S;               // проміжна змінна: подвоєна площа
    double h = twoS / a;               // вихідна змінна: висота, проведена до сторони a

    cout << "Висота трикутника h = " << h << endl;
    return 0;
}
